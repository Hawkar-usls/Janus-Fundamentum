#!/usr/bin/env python3
"""R5 E60 anti-loop controls for the arbitrary-(P,Q) route.

This checker freezes four distinctions that must not be conflated:

1) A square simple cubic incidence matrix is exactly a 3-regular bipartite graph.
   Any such graph decomposes into three perfect matchings, hence after relabelling
   columns it has normal form I+P+Q.  Therefore permutation factorization itself
   does not define a smaller/easier class.

2) In the bipartite row-column graph, the union of the P and Q matchings is
   2-regular and decomposes into alternating cycles.  Those cycles are NOT in
   general invariant components of the full matrix, because the I matching can
   connect them.

3) The invariant blocks are the orbits of <p,q> on the common index set.  Their
   Schreier graph need not be a cycle.

4) The tempting degree-2 flow/b-factor relaxation is vacuous here: P+Q itself is
   already a 2-factor of the cubic bipartite incidence graph for every input.
   Exact-One instead requires an all-or-none choice of the three incidences of a
   column variable.
"""
from collections import deque


def assert_perm(p):
    assert sorted(p) == list(range(len(p)))


def build_rows(p, q):
    n = len(p)
    assert_perm(p); assert_perm(q); assert len(q) == n
    rows = []
    for i in range(n):
        R = {i, p[i], q[i]}
        assert len(R) == 3
        rows.append(R)
    assert all(sum(j in rows[i] for i in range(n)) == 3 for j in range(n))
    return rows


def orbit_components(p, q):
    """Components of the Schreier graph generated by p,q and their inverses."""
    n = len(p)
    pinv = [0]*n; qinv = [0]*n
    for i,j in enumerate(p): pinv[j] = i
    for i,j in enumerate(q): qinv[j] = i
    seen = set(); comps = []
    for s in range(n):
        if s in seen: continue
        C = set([s]); seen.add(s); dq = deque([s])
        while dq:
            v = dq.popleft()
            for w in (p[v], q[v], pinv[v], qinv[v]):
                if w not in seen:
                    seen.add(w); C.add(w); dq.append(w)
        comps.append(C)
    return comps


def schreier_undirected_degrees(p, q):
    n = len(p)
    adj = [set() for _ in range(n)]
    for i in range(n):
        for j in (p[i], q[i]):
            adj[i].add(j); adj[j].add(i)
    return [len(a) for a in adj]


def pq_bipartite_components(p, q):
    """Components using only P,Q edges in the bipartite row/column graph."""
    n = len(p)
    adj = [[] for _ in range(2*n)]
    for i in range(n):
        for j in (p[i], q[i]):
            r = i
            c = n+j
            adj[r].append(c); adj[c].append(r)
    assert all(len(a) == 2 for a in adj)
    seen = set(); comps=[]
    for s in range(2*n):
        if s in seen: continue
        C=set([s]); seen.add(s); dq=deque([s])
        while dq:
            v=dq.popleft()
            for w in adj[v]:
                if w not in seen:
                    seen.add(w); C.add(w); dq.append(w)
        comps.append(C)
    return comps


def full_bipartite_components(p, q):
    """Components after adding I edges to the same bipartite graph."""
    n = len(p)
    adj = [[] for _ in range(2*n)]
    for i in range(n):
        for j in (i,p[i],q[i]):
            r=i; c=n+j
            adj[r].append(c); adj[c].append(r)
    assert all(len(a) == 3 for a in adj)
    seen=set(); comps=[]
    for s in range(2*n):
        if s in seen: continue
        C={s}; seen.add(s); dq=deque([s])
        while dq:
            v=dq.popleft()
            for w in adj[v]:
                if w not in seen:
                    seen.add(w); C.add(w); dq.append(w)
        comps.append(C)
    return comps


def exact_one_exists(rows):
    n = len(rows)
    for mask in range(1 << n):
        ok = True
        for R in rows:
            if sum((mask >> j) & 1 for j in R) != 1:
                ok = False; break
        if ok:
            return True
    return False


def check_cycle_vs_orbit_counterexample():
    # p=+1 and q=+5 on Z_12.  <p,q> is transitive because p alone is a 12-cycle.
    # But P+Q in the bipartite graph splits into 4 alternating 6-cycles.
    # The I matching reconnects those four cycles into one full component.
    n = 12
    p = [(i+1) % n for i in range(n)]
    q = [(i+5) % n for i in range(n)]
    build_rows(p,q)
    orbits = orbit_components(p,q)
    pq_cycles = pq_bipartite_components(p,q)
    full = full_bipartite_components(p,q)
    deg = schreier_undirected_degrees(p,q)
    assert len(orbits) == 1 and len(orbits[0]) == n
    assert len(pq_cycles) == 4
    assert sorted(len(C) for C in pq_cycles) == [6,6,6,6]
    assert len(full) == 1 and len(full[0]) == 2*n
    assert all(d == 4 for d in deg)
    print("cycle/orbit separation: PASS (4 P+Q cycles, 1 <p,q> orbit, Schreier degree 4)")


def check_flow_relaxation_counterexample():
    # Frozen E58 UNSAT9 fixture: Exact-One is false.
    p = [4,0,6,7,8,1,5,2,3]
    q = [8,7,1,6,3,0,4,5,2]
    rows = build_rows(p,q)
    assert not exact_one_exists(rows)

    # Yet P+Q itself gives degree exactly 2 at every row and every column.
    n = len(p)
    row_deg = [2] * n
    col_deg = [0] * n
    for i in range(n):
        col_deg[p[i]] += 1
        col_deg[q[i]] += 1
    assert row_deg == [2]*n
    assert col_deg == [2]*n
    print("degree-2 flow relaxation: PASS (feasible on frozen Exact-One UNSAT9)")


def check_f3_parity_non_equivalence():
    # x=1 is always a binary parity solution because every row has 3 ones,
    # but it is not Exact-One: every integer row sum is 3. Under r=1+x in F3,
    # r=2*1 and each row sums to 6 == 0, not 1.
    p = [2,6,7,4,5,8,1,3,0]
    q = [5,8,1,6,3,2,0,4,7]
    rows = build_rows(p,q)
    n=len(p)
    x=[1]*n
    parity=[sum(x[j] for j in R)%2 for R in rows]
    integer=[sum(x[j] for j in R) for R in rows]
    r=[2]*n
    ternary=[sum(r[j] for j in R)%3 for R in rows]
    assert parity == [1]*n
    assert integer == [3]*n
    assert ternary == [0]*n
    print("F3 distinction: PASS (parity Ax=1 does not imply full-support ternary Ar=1)")


def main():
    check_cycle_vs_orbit_counterexample()
    check_flow_relaxation_counterexample()
    check_f3_parity_non_equivalence()
    print("R5 E60 permutation-factorization anti-loop controls: PASS")


if __name__ == "__main__":
    main()
