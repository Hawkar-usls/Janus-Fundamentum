def source_symmetry_actions(k,edges,idx,rows):
    assert k==5
    n=len(rows)
    vals=tuple(sorted(edges))
    actions=[]
    by_row={row:i for i,row in enumerate(rows)}
    for rotation in range(k):
        for flip in (0,1):
            perm=[0]*n
            for e in vals:
                mapped=tuple(sorted(
                    (4*((v//4+rotation)%k)+v%4) for v in e
                ))
                assert mapped in vals,(e,mapped)
                for color in range(3):
                    next_color=(1-color if color in (0,1) else 2) if flip else color
                    perm[idx[(e,color)]]=idx[(mapped,next_color)]
            assert sorted(perm)==list(range(n))
            row_map=[]
            for row in rows:
                transformed=tuple(sorted(perm[v] for v in row))
                assert transformed in by_row,"invalid source automorphism"
                row_map.append(by_row[transformed])
            assert sorted(row_map)==list(range(n))
            actions.append((tuple(perm),tuple(row_map)))
    assert len(actions)==10
    assert actions[0][0]==tuple(range(n))
    return tuple(actions)


def source_moment_orbits(n,actions):
    monomials,keys=multilinear_monomials(n,3)
    mon_orbits={}
    orbit_keys=[]
    orbit_index=[]
    for M in monomials:
        canon=min(
            tuple(sorted(p[v] for v in M))
            for p,r in actions
        )
        if canon not in mon_orbits:
            mon_orbits[canon]=len(orbit_keys)
            orbit_keys.append(canon)
        orbit_index.append(mon_orbits[canon])
    assert orbit_keys[0]==()
    assert all(orbit_index[key[tuple(sorted(p[v] for v in M))]]==orbit_index[j]
               for j,M in enumerate(monomials[:100])
               for p,r in actions)
    return monomials,keys,tuple(orbit_index),tuple(orbit_keys)


def row_orbit_representatives(n,actions):
    remaining=set(range(n))
    chosen=[]
    while remaining:
        rep=min(remaining)
        orbit={r[rep] for p,r in actions}
        assert orbit<=remaining
        chosen.append(rep)
        remaining-=orbit
    assert not remaining
    return tuple(chosen)


def reduce_sparse(row,basis):
    while row:
        pivot=max(row)
        if pivot not in basis:
            coeff=row[pivot]
            assert coeff in (1,2)
            if coeff==2:
                row={x:(2*c)%3 for x,c in row.items()}
            assert row[pivot]==1
            basis[pivot]=row
            return pivot
        old=basis[pivot]
        coeff=row[pivot]
        for x,c in old.items():
            value=(row.get(x,0)-coeff*c)%3
            if value:row[x]=value
            elif x in row:del row[x]
    return None


def orbit_degree3_dual(rows,n,actions):
    monoms,keys,oid,orbits=source_moment_orbits(n,actions)
    assert len(orbits)<=len(monoms)
    reps=row_orbit_representatives(n,actions)
    generators=monoms[:1+n+n*(n-1)//2]
    basis={}
    processed=0
    for row_i in reps:
        clause=rows[row_i]
        for M in generators:
            processed+=1
            coeff={}
            def add(j,c):
                v=(coeff.get(j,0)+c)%3
                if v:coeff[j]=v
                elif j in coeff:del coeff[j]
            add(oid[keys[M]],-1)
            for v in clause:
                tup=tuple(sorted(set(M)|{v}))
                add(oid[keys[tup]],1)
            pivot=reduce_sparse(coeff,basis)
            if pivot==0:
                return {"status":"NO_DEGREE3_DUAL_INVARIANT_REFUTATION_CANDIDATE",
                        "ambient_orbit_dim":len(orbits),"rank":len(basis),
                        "source_row_representatives":len(reps),
                        "generator_orbits_processed":processed}

    assert 0 not in basis
    values={0:1}
    for pivot in sorted(basis):
        row=basis[pivot]
        assert row[pivot]==1 and all(j<=pivot for j in row)
        values[pivot]=(-sum(c*values.get(j,0)
                             for j,c in row.items() if j!=pivot))%3
    sparse_orbit_dual={i:v for i,v in values.items() if v}
    full={key:c for key,(m,c) in enumerate(
        zip(monoms,(values.get(i,0) for i in oid))) if c}
    assert full.get(0)==1
    assert verify_dual_source(rows,n,full,monoms,keys)==n*len(generators)
    # Every G-invariance equation independently checked on all
    # original monomials, not merely on compressed source generators.
    for mon_i,M in enumerate(monoms):
        for perm,rperm in actions:
            target=tuple(sorted(perm[v] for v in M))
            assert full.get(keys[target],0)==full.get(mon_i,0)
    return {"status":"SOURCE_CERTIFIED_GF3_DEGREE3_DUAL",
            "ambient_orbit_dim":len(orbits),
            "full_ambient_dim":len(monoms),
            "rank":len(basis),
            "source_row_representatives":len(reps),
            "generator_orbits_processed":processed,
            "dual_support":len(full),
            "orbit_dual_support":len(sparse_orbit_dual),
            "full_dual":full}


