#!/usr/bin/env python3
"""R5 E117: mixed-normal leakage is rank-one quotient-parallel propagation.

After E106, every active rank-2 ExactOne check has three distinct nonzero
coordinate normals g1,g2,g3 in U* with

    g1 + g2 + g3 = 0.

Its forbidden character phi is linear on their 2-space, so the three incidence
marks p_i=phi(g_i) also satisfy

    p1 + p2 + p3 = 0  over GF(2).

Fix any already-understood normal subspace W <= U* (for example an E113-E116
signed cographic core span).

A rank-2 check line can meet W in only three possible ways:
  * 0 of its three nonzero normals lie in W -> intersection rank 0;
  * exactly 1 lies in W                 -> intersection rank 1;
  * all 3 lie in W                      -> intersection rank 2.

Exactly TWO is impossible because the third is their sum.

Therefore genuine mixed-normal leakage from W has the unique form

    g0 in W,
    a,b notin W,
    a+b=g0.

Modulo W,

    a_bar = b_bar != 0.

So a leaking check introduces exactly ONE new quotient-normal direction even
though it exposes two outside Tanner variables.  Its support/forbidden marks
obey

    p_a xor p_b = p_g0.

Hence:
  * if p_g0=1, the two outside copies are a signed-parallel pair in U*/W;
  * if p_g0=0, they are a same-sign parallel pair in U*/W.

Every leakage step grows the normal span by exactly one dimension and exports
one quotient-parallel pair.  This is a universal local theorem; it does not
assume cographicity beyond the choice of the starting core W.

P_VS_NP remains OPEN.
"""


def xor(*xs):
    z=0
    for x in xs:
        z^=x
    return z


def span(vectors):
    B=[]
    for x in vectors:
        y=x
        for b in B:
            y=min(y,y^b)
        if y:
            # insert and keep triangular enough for membership tests
            hb=y.bit_length()
            B=[min(b,b^y) if b.bit_length()==hb else b for b in B]
            B.append(y)
            B.sort(reverse=True)
    return tuple(B)


def in_span(x,B):
    y=x
    for b in B:
        y=min(y,y^b)
    return y==0


def rank(vectors):
    return len(span(vectors))


def quotient_equal_mod_W(a,b,W):
    return in_span(a^b,W)


def classify_line(g1,g2,W):
    g3=g1^g2
    assert g1 and g2 and g3
    assert len({g1,g2,g3})==3
    inside=[g for g in (g1,g2,g3) if in_span(g,W)]
    return g3,inside


def exhaustive_small_firewall():
    # Work in F2^4.  Exhaust all 2D lines and all subspaces generated by up to
    # three ambient vectors; verify 0/1/3 intersection classification.
    ambient=range(1,16)
    subspaces=set()
    subspaces.add(())
    for a in ambient:
        subspaces.add(tuple(sorted(span((a,)))))
    for a in ambient:
        for b in ambient:
            subspaces.add(tuple(sorted(span((a,b)))))
    for a in ambient:
        for b in ambient:
            for c in ambient:
                subspaces.add(tuple(sorted(span((a,b,c)))))

    counts={0:0,1:0,3:0}
    leak_examples=0

    seen_lines=set()
    for g1 in ambient:
        for g2 in ambient:
            if g1==g2:
                continue
            g3=g1^g2
            if not g3:
                continue
            line=tuple(sorted((g1,g2,g3)))
            if line in seen_lines:
                continue
            seen_lines.add(line)

            for WB in subspaces:
                W=span(WB)
                g3,inside=classify_line(g1,g2,W)
                k=len(inside)
                assert k in (0,1,3)
                counts[k]+=1

                if k==1:
                    core=inside[0]
                    outside=[g for g in (g1,g2,g3) if g!=core]
                    a,b=outside
                    assert not in_span(a,W)
                    assert not in_span(b,W)
                    assert quotient_equal_mod_W(a,b,W)
                    assert rank(tuple(W)+(g1,g2))==rank(W)+1
                    leak_examples+=1

    assert counts[0]>0 and counts[1]>0 and counts[3]>0
    assert leak_examples>0
    return len(seen_lines),len(subspaces),counts,leak_examples


def verify_mark_rule():
    # phi is any linear character on a binary 2-space.  Values on g1,g2 are
    # arbitrary; value on g3=g1+g2 is their XOR.
    seen=set()
    for p1 in (0,1):
        for p2 in (0,1):
            p3=p1^p2
            assert p1^p2^p3==0
            # If g1 is the unique core normal, the two outside marks satisfy
            # p2 xor p3 = p1.
            assert p2^p3==p1
            seen.add((p1,p2,p3))
    assert len(seen)==4


def main():
    lines,subs,counts,leaks=exhaustive_small_firewall()
    verify_mark_rule()

    print("R5 E117 mixed-normal leakage rank-one parallel propagation: PASS")
    print("F2^4 lines checked=",lines,"subspaces checked=",subs)
    print("line/W incidence counts=",counts)
    print("rank-one leakage examples checked=",leaks)
    print("exactly-two-core-normal case = impossible")
    print("1-core + 2-outside => one new quotient direction, outside normals parallel mod W")
    print("core mark 1 => signed-parallel quotient pair; core mark 0 => same-sign pair")
    print("next target: recursive leakage graph / rank-growth separator theorem")
    print("P_VS_NP remains OPEN")


if __name__=="__main__":
    main()
