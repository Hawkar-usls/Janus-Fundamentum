#!/usr/bin/env python3
import json

L=7
N=L*L
M=N+1

def rref_basis(vs):
    B={}
    for x in vs:
        y=x
        for p in sorted(B,reverse=True):
            if (y>>p)&1: y^=B[p]
        if y:
            p=y.bit_length()-1
            for q in list(B):
                if (B[q]>>p)&1: B[q]^=y
            B[p]=y
    ps=sorted(B,reverse=True)
    for p in ps:
        for q in ps:
            if q!=p and ((B[q]>>p)&1): B[q]^=B[p]
    return tuple(B[p] for p in sorted(B,reverse=True))

def rank(vs): return len(rref_basis(vs))

def row_rref(rows,n):
    A=rows[:]; piv=[]; r=0
    for c in range(n):
        k=next((i for i in range(r,len(A)) if (A[i]>>c)&1),None)
        if k is None: continue
        A[r],A[k]=A[k],A[r]
        for i in range(len(A)):
            if i!=r and ((A[i]>>c)&1): A[i]^=A[r]
        piv.append(c); r+=1
        if r==len(A): break
    return A[:r],piv

def nullspace_basis(rows,n):
    rr,piv=row_rref(rows,n)
    free=[c for c in range(n) if c not in piv]
    out=[]
    for f in free:
        x=1<<f
        for row,p in zip(rr,piv):
            if (row>>f)&1: x|=1<<p
        assert all(((row&x).bit_count()&1)==0 for row in rows)
        out.append(x)
    return out,len(piv)

# H = I + P_x + P_y on Z_7^2.
rows=[]
for i in range(L):
    for j in range(L):
        x=0
        for a,b in ((i,j),((i+1)%L,j),(i,(j+1)%L)):
            x ^= 1<<(a*L+b)
        rows.append(x)
assert all(x.bit_count()==3 for x in rows)
colw=[sum((row>>c)&1 for row in rows) for c in range(N)]
assert set(colw)=={3}

K,rH=nullspace_basis(rows,N)
assert rH==43 and len(K)==6

# Parent cocycle code is the even extension of rowspan(H).
# A dual representation has ordinary columns (kernel-column-signature,1)
# and f=(0,1).
dual_cols=[]
for j in range(N):
    sig=0
    for i,b in enumerate(K):
        if (b>>j)&1: sig|=1<<i
    dual_cols.append(sig | (1<<len(K)))
dual_cols.append(1<<len(K))
assert len(set(dual_cols))==M and 0 not in dual_cols
assert all((x>>len(K))&1 for x in dual_cols)

# Distinct nonzero dual columns exclude cocycles of weight 1 or 2;
# three such columns cannot sum to zero because their last coordinates
# sum to 1. Cubic star rows have weight 4.
gstar=4
rM=rH

# Exact circuit-girth control. The cycle code is ker(H) (with f=0)
# plus the all-ground-set cycle.
kernel_weights=[]
for mask in range(1,1<<len(K)):
    z=0
    for i,b in enumerate(K):
        if (mask>>i)&1: z^=b
    kernel_weights.append(z.bit_count())
cycle_weights=kernel_weights + [M] + [M-w for w in kernel_weights]
circuit_girth=min(cycle_weights)
assert circuit_girth==22

q_lb=rM-((2*M-1)//gstar)
assert q_lb==19

# Enumerate all flats generated by subsets of the dual ground set.
flats={()}
for v in dual_cols:
    new=set(flats)
    for b in flats:
        new.add(rref_basis((*b,v)))
    flats=new
assert len(flats)==23250

def in_span(x,b):
    B={v.bit_length()-1:v for v in b}
    y=x
    for p in sorted(B,reverse=True):
        if (y>>p)&1:y^=B[p]
    return y==0

sep12=0; sep3=0; min_lambda=99
for b in flats:
    A=[x for x in dual_cols if in_span(x,b)]
    if not A or len(A)==M: continue
    B=[x for x in dual_cols if not in_span(x,b)]
    ra=rank(A); rb=rank(B)
    lam=ra+rb-7
    if len(A)>=2 and len(B)>=2:
        min_lambda=min(min_lambda,lam)
        if lam<2: sep12+=1
    if len(A)>=3 and len(B)>=3 and lam==2:
        sep3+=1
assert min_lambda==2 and sep12==0 and sep3==0

# Why flat enumeration is complete here:
# girth=22 and cogirth=4 imply no triangles or triads. Any exact
# 3-separation can therefore be closed on one side by moving elements
# from the opposite side that lie in its closure without shrinking the
# opposite side below 4. Hence a flat-side representative would appear
# in the census above.

# S8 minor in the self-dual dual representation.
# Contract dual elements 0,1,2; the quotient simplification is PG(3,2).
contract=(0,1,2)
Cb=rref_basis([dual_cols[i] for i in contract])
pivs=[x.bit_length()-1 for x in Cb]
free=[i for i in range(7) if i not in pivs]
assert len(free)==4

def qcoord(x):
    B={v.bit_length()-1:v for v in Cb}
    y=x
    for p in sorted(B,reverse=True):
        if (y>>p)&1:y^=B[p]
    q=0
    for j,pos in enumerate(free):
        if (y>>pos)&1:q|=1<<j
    return q

qpts=[(i,qcoord(x)) for i,x in enumerate(dual_cols) if i not in contract]
assert {v for _,v in qpts if v}==set(range(1,16))
keep=(18,19,9,3,16,6,13,4)
target={qcoord(dual_cols[i]) for i in keep}
assert target=={1,4,5,6,12,13,14,15}
S8={1,2,4,8,14,13,11,15}
images=(4,12,15,6)
def lin(x):
    y=0
    for i in range(4):
        if (x>>i)&1:y^=images[i]
    return y
assert {lin(x) for x in S8}==target

# Every deletion has rank 43 and cogirth exactly 3. The all-ground-set
# cycle excludes coloops. Puncturing a distance-4 cocycle code gives
# distance >=3, and every coordinate belongs to a cubic star cocycle,
# so the punctured distance is exactly 3.
deletions=[(43,3)]*M

# Graft lane: deleting the graft element would be graphic. A simple
# graphic matroid with r=43,m=49 has a graph of average degree <3,
# hence a bond of size <=2, contradicting deletion cogirth 3.
graft_excluded=True

# Even-cut lane: C*(M) would contain a graph cycle-space of dimension
# >=42, so graph rank <=8. Cogirth 4 forces that graph to be simple
# triangle-free. Componentwise Mantel gives <=20 edges at total rank 8.
def parts(n,lo=1):
    if n==0:
        yield (); return
    for x in range(lo,n+1):
        for rest in parts(n-x,x): yield (x,)+rest
mantel_max=0
for P in parts(8):
    mantel_max=max(mantel_max,sum(((r+1)*(r+1))//4 for r in P))
assert mantel_max==20 < M

out={
  "status":"PASS_TORUS_L7_ACTUAL_LIVE_LEAF_STRESS",
  "parent":{"L":L,"ordinary_elements":N,"elements":M,
            "H":"I+P_x+P_y on Z_7^2","rank":rM,
            "nullity_H":len(K),"cogirth":gstar},
  "q_graph_certificate":{"lower_bound":q_lb,
                         "formula":"r-floor((2m-1)/g*)",
                         "r":rM,"m":M,"gstar":gstar},
  "connectivity":{"dual_rank":7,"generated_flats":len(flats),
                  "three_connected":True,
                  "exact_three_separations":sep3,
                  "circuit_girth":circuit_girth},
  "s8_minor_dual":{"self_dual_S8":True,"contract":contract,
                   "keep":keep,"target_points":sorted(target),
                   "gl4_basis_images":images,
                   "quotient_simple_points":15},
  "terminal_controls":{"no_S8_excluded":True,
      "graphic_even_cycle_excluded_by_q_graph":True,
      "graft_excluded":graft_excluded,
      "all_deletions_rank_cogirth":deletions,
      "even_cut_excluded":True,
      "triangle_free_edge_ceiling_rank8":mantel_max},
  "scope":{"asymptotic_omega_log_family":"NOT_PROVED",
           "global_solver_promotion":"HOLD",
           "P_VS_NP":"OPEN","P_EQ_NP":"NOT_PROVED"}
}
print(json.dumps(out,sort_keys=True))
