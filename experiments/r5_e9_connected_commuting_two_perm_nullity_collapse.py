#!/usr/bin/env python3
"""Exact finite regression for CCN-1.

The theorem itself is proved symbolically in the companion research note.
This checker samples all generating pairs on a deterministic collection of
small two-generated finite abelian groups and verifies exact Q-nullity in
{0,2}.  It also verifies a disconnected commuting control with nullity 4.
"""

from fractions import Fraction
from itertools import product


def rank_q(mat):
    a = [[Fraction(x) for x in row] for row in mat]
    m = len(a)
    n = len(a[0]) if m else 0
    r = 0
    for c in range(n):
        pivot = next((i for i in range(r, m) if a[i][c] != 0), None)
        if pivot is None:
            continue
        a[r], a[pivot] = a[pivot], a[r]
        z = a[r][c]
        a[r] = [v / z for v in a[r]]
        for i in range(m):
            if i != r and a[i][c] != 0:
                z = a[i][c]
                a[i] = [a[i][j] - z * a[r][j] for j in range(n)]
        r += 1
        if r == m:
            break
    return r


def add(x, y, mod):
    return tuple((x[i] + y[i]) % mod[i] for i in range(len(mod)))


def neg(x, mod):
    return tuple((-x[i]) % mod[i] for i in range(len(mod)))


def elements(mod):
    return list(product(*[range(k) for k in mod]))


def generates(mod, p, q):
    zero = tuple(0 for _ in mod)
    seen = {zero}
    stack = [zero]
    steps = (p, q, neg(p, mod), neg(q, mod))
    while stack:
        x = stack.pop()
        for s in steps:
            y = add(x, s, mod)
            if y not in seen:
                seen.add(y)
                stack.append(y)
    return len(seen) == len(elements(mod))


def translation_matrix(mod, step):
    pts = elements(mod)
    idx = {x: i for i, x in enumerate(pts)}
    n = len(pts)
    out = [[0] * n for _ in range(n)]
    for x in pts:
        out[idx[x]][idx[add(x, step, mod)]] = 1
    return out


def i_plus_p_plus_q(mod, p, q):
    P = translation_matrix(mod, p)
    Q = translation_matrix(mod, q)
    n = len(P)
    return [[(1 if i == j else 0) + P[i][j] + Q[i][j]
             for j in range(n)] for i in range(n)]


def nullity_q(mat):
    return len(mat[0]) - rank_q(mat)


def block_diag(a, b):
    na, nb = len(a), len(b)
    out = [[0] * (na + nb) for _ in range(na + nb)]
    for i in range(na):
        for j in range(na):
            out[i][j] = a[i][j]
    for i in range(nb):
        for j in range(nb):
            out[na + i][na + j] = b[i][j]
    return out


def main():
    # Every tested group is finite abelian and generated by <=2 elements.
    # Keep total order modest so this exact-Fraction CI remains fast.
    groups = []
    groups += [(m,) for m in range(2, 19)]
    groups += [
        (2, 2), (2, 3), (2, 4), (2, 5), (2, 6),
        (3, 3), (3, 4), (3, 5), (4, 4), (4, 5),
    ]

    checked = 0
    singular = 0
    max_nullity = 0
    for mod in groups:
        pts = elements(mod)
        for p in pts:
            for q in pts:
                if not generates(mod, p, q):
                    continue
                A = i_plus_p_plus_q(mod, p, q)
                nu = nullity_q(A)
                assert nu in (0, 2), (mod, p, q, nu)
                checked += 1
                singular += (nu == 2)
                max_nullity = max(max_nullity, nu)

    # Sharp connected example: Z3 with p=1,q=2 gives J3, nullity 2.
    A3 = i_plus_p_plus_q((3,), (1,), (2,))
    assert nullity_q(A3) == 2

    # Connectedness is necessary: two invariant copies add their kernels.
    disconnected = block_diag(A3, A3)
    assert nullity_q(disconnected) == 4

    print("CCN-1 exact finite regression: PASS")
    print(f"generating pairs checked = {checked}")
    print(f"singular connected cases = {singular}")
    print(f"max connected nullity = {max_nullity}")
    print("disconnected control nullity = 4")


if __name__ == "__main__":
    main()
