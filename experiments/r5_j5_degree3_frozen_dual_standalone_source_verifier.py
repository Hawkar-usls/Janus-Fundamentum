"""STANDALONE independently checked FROZEN J5/SCL90 degree3 counterexample.

Reads FROZEN compressed orbit moment bytes from a repository file,
NOT generated by the orbit Gaussian elimination being verified.
Regenerates entire ORIGINAL source from Isaacs J5 native Holyer
mapping, checks original source UNSAT by independent 27-state transfer,
builds all exact 121576 original 0/1 multilinear monomials and
all 6656 G=C10 x C2 orbits, EXPANDS the stored 6656-byte
F3 pseudomoment vector to full degree3 dual y.

An independent original-row checker tests:
  y(1)=1,
  0 = -y(x_M) + sum_(v in original clause i) y(x_(M union {v}))
for ALL 90 source rows and ALL 4096 monomials |M|<=2,
i.e. ALL 368640 original generator multipliers.

This is a normal stand-alone certificate verifier with NO
Gaussian elimination, no SAT solver for the original source,
no heuristic approximations, and no untrusted output claims.
Source original UNSAT and dual no-degree3 are independent
mathematical checks. Proof of contradiction:
if 1 = sum c_i,M E_i*x_M with |M|<=2, applying y gives 1=0 mod3.
"""
from __future__ import annotations
import base64
import hashlib
import zlib
from pathlib import Path
from itertools import combinations
from r5_universal_cubic_flow_lowmoment_collision_20v import flower
from r5_universal_cubic_edgecolor_direct_scl_bridge import make_scl
from r5_universal_flower_27state_transfer_unsat_certificate import (
    verify_authenticated_flower_unsat
)
from r5_universal_exact_support_residual_dag_attack import validate_sparse
from r5_universal_flower_j5_gf3_degree3_symmetry_dual import (
    source_symmetry_actions,source_moment_orbits
)

PATH=Path("research/certificates/R5_J5_SCL90_GF3_V3_ORBIT_DUAL_2026-10-13.b64z")
EXPECTED_ORBITS=6656
EXPECTED_MONOMIALS=121576
EXPECTED_ORIGINAL_GENERATORS=368640
EXPECTED_SHA256="f2944e1a4fb474ebaac3aa2fcc19689139d1bee256f3f01af1f4ecebfd7c1edd"


def independent_original_dual_checker(rows,n,monoms,keys,dual):
    """Deliberately independent of solver/other dual check functions."""
    assert n==90
    assert len(dual)==len(monoms)
    assert len(monoms)==EXPECTED_MONOMIALS
    assert dual[keys[()]]==1
    assert all(c in (0,1,2) for c in dual)
    generators=0
    for i,row in enumerate(rows):
        assert len(row)==3 and all(0<=v<n for v in row)
        for degree in range(3):
            for M in combinations(range(n),degree):
                lhs=-dual[keys[M]]
                for v in row:
                    t=tuple(sorted(set(M)|{v}))
                    lhs+=dual[keys[t]]
                assert lhs%3==0,(
                    "FORGED_ORBIT_DUAL",i,M,lhs%3
                )
                generators+=1
    assert generators==EXPECTED_ORIGINAL_GENERATORS
    return generators


def main():
    rows,n,edges,idx=make_scl(flower(5))
    assert n==90 and validate_sparse(rows,n)==rows
    assert verify_authenticated_flower_unsat(rows,n,5)
    assert PATH.is_file(),PATH
    encoded=PATH.read_text("ascii").strip()
    assert encoded and all(c in
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/="
        for c in encoded)
    raw=zlib.decompress(base64.b64decode(encoded,validate=True))
    assert len(raw)==EXPECTED_ORBITS and set(raw)<=set((0,1,2))
    # Fingerprint printed so frozen certificate can be independently
    # compared to the original dual discovery workflow.
    hash_sha256=hashlib.sha256(raw).hexdigest()
    assert hash_sha256==EXPECTED_SHA256, "FROZEN_DUAL_SHA256_MISMATCH"
    actions=source_symmetry_actions(5,edges,idx,rows)
    monoms,keys,orbit_ids,orbit_keys=source_moment_orbits(n,actions)
    assert len(orbit_keys)==EXPECTED_ORBITS
    y=tuple(raw[oid] for oid in orbit_ids)
    checks=independent_original_dual_checker(
        rows,n,monoms,keys,y
    )
    print(f"FROZEN_SOURCE_J5_SCL90_UNSAT=SOURCE_27STATE_TRANSFER_PROVED",
          flush=True)
    print(f"FROZEN_GF3_V3_DUAL_ORBIT_COUNT={len(raw)} "
          f"SHA256={hash_sha256}",flush=True)
    print(f"FROZEN_GF3_V3_DUAL_FULL_SUPPORT="
          f"{sum(c!=0 for c in y)}",flush=True)
    print(f"FROZEN_GF3_V3_ORIGINAL_GENERATORS_CHECKED={checks}",
          flush=True)
    # An untrusted altered witness must be rejected by the
    # stand-alone direct original source algebraic checker.
    forged=list(y)
    forged[keys[()]]=0
    try:
        independent_original_dual_checker(
            rows,n,monoms,keys,tuple(forged)
        )
    except AssertionError:
        print("FROZEN_GF3_V3_FORGED_CERTIFICATE_REJECTED=PASS",
              flush=True)
    else:
        raise AssertionError("forged dual unexpectedly accepted")
    print("ALL_SCL_GF3_DEGREE3_UNSAT_COMPLETENESS=REFUTED_BY_SOURCE_J5")
    print("SOURCE_J5_GF3_BOOLEAN_MIN_REFUTATION_DEGREE_GE4=PROVED")
    print("UNIVERSAL_FIXED_DEGREE_D_EXISTENCE=OPEN")
    print("UNIVERSAL_POLY_SOLVELINEARCUBICXSAT=NOT_CONSTRUCTED")
    print("P_VS_NP=OPEN")


if __name__=="__main__":
    main()
